function getSeedImageOffset(seed) {
  return String(seed)
    .split("")
    .reduce((total, character) => total + character.charCodeAt(0), 0) %
    REAL_ESTATE_IMAGE_URLS.length;
}

function buildImageUrls(seed) {
  const offset = getSeedImageOffset(seed);

  return [0, 1, 2].map((index) => ({
    url: REAL_ESTATE_IMAGE_URLS[
      (offset + index) % REAL_ESTATE_IMAGE_URLS.length
    ],
    publicId: null,
  }));
}

